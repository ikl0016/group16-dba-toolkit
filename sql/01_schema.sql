-- =====================================================================
-- 01_schema.sql  |  Module 1 (Doreen Lobe): schema for the
-- order-processing workload.
--
-- Design notes (why it looks like this):
--   * Only the indexes PostgreSQL creates automatically exist at the
--     start: one per PRIMARY KEY and one per UNIQUE constraint.
--     PostgreSQL does NOT index foreign-key columns automatically, so
--     orders.customer_id and order_items.order_id start unindexed.
--     That is the realistic "missing index" problem we diagnose.
--   * autovacuum_enabled = false on the two big tables keeps planner
--     statistics under OUR control during experiments (we run ANALYZE
--     explicitly). In production you would leave autovacuum on.
--   * Fixed reference date 2026-11-01 (no now()) so every team member
--     gets the same data and the same query results.
-- =====================================================================

DROP SCHEMA IF EXISTS shop CASCADE;
CREATE SCHEMA shop;

CREATE TABLE shop.customers (
    customer_id   integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email         text        NOT NULL UNIQUE,
    full_name     text        NOT NULL,
    city          text        NOT NULL,
    state         char(2)     NOT NULL,
    loyalty_tier  text        NOT NULL
                  CHECK (loyalty_tier IN ('bronze','silver','gold','platinum')),
    signup_date   date        NOT NULL
);

CREATE TABLE shop.products (
    product_id    integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sku           text          NOT NULL UNIQUE,
    product_name  text          NOT NULL,
    category      text          NOT NULL,
    unit_price    numeric(10,2) NOT NULL CHECK (unit_price > 0),
    is_active     boolean       NOT NULL DEFAULT true
);

CREATE TABLE shop.orders (
    order_id      bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id   integer       NOT NULL REFERENCES shop.customers(customer_id),
    order_date    timestamp     NOT NULL,
    status        text          NOT NULL
                  CHECK (status IN ('pending','processing','shipped',
                                    'delivered','cancelled','returned')),
    ship_city     text          NOT NULL,
    ship_state    char(2)       NOT NULL,
    total_amount  numeric(12,2) NOT NULL DEFAULT 0 CHECK (total_amount >= 0)
) WITH (autovacuum_enabled = false);

CREATE TABLE shop.order_items (
    order_item_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id      bigint        NOT NULL REFERENCES shop.orders(order_id),
    product_id    integer       NOT NULL REFERENCES shop.products(product_id),
    quantity      integer       NOT NULL CHECK (quantity BETWEEN 1 AND 20),
    unit_price    numeric(10,2) NOT NULL CHECK (unit_price > 0)
) WITH (autovacuum_enabled = false);

-- Reporting view used in the demo to show the data is consistent.
CREATE VIEW shop.v_customer_order_totals AS
SELECT c.customer_id,
       c.email,
       c.loyalty_tier,
       count(o.order_id)              AS order_count,
       coalesce(sum(o.total_amount),0) AS lifetime_value
FROM shop.customers c
LEFT JOIN shop.orders o ON o.customer_id = c.customer_id
GROUP BY c.customer_id, c.email, c.loyalty_tier;
